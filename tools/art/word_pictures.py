ENDINGS = "다기는고음은게어아히하며지을를이가의에도"


def has_key(seg, k):
    """두 글자 이상 낱말은 들어 있으면. 한 글자 낱말은 띄어 쓴 낱말이 그 글자로 시작하고, 그 글자뿐이거나
    바로 뒤가 끝말(다·기·는·음 …, 조사)일 때만(적 → 적이·적의는 되고 적인·적당은 안 된다)."""
    if len(k) >= 2:
        return k in seg
    for tok in seg.replace("(", " ").replace(")", " ").replace("~", " ").replace(".", " ").split():
        if tok.startswith(k) and (len(tok) == 1 or tok[1] in ENDINGS):
            return True
    return False


def pick(data, w):
    """src/domain/art/word_picture.gd의 pick과 같은 규칙(보기·통계용)."""
    segs = [s.strip() for s in w["meaning"].replace(",", ";").split(";") if s.strip()]
    roots = [e["meaning"] for e in w.get("etym", []) if not e["root"].strip().endswith("-")]
    pref = [e["meaning"] for e in w.get("etym", []) if e["root"].strip().endswith("-")]
    glyph = ""
    for s in segs + roots:
        for g in data["glyphs"]:
            if any(has_key(s, k) for k in g["keys"]):
                glyph = g["id"]
                break
        if glyph:
            break
    mod = ""
    for s in pref:
        for m in data["mods"]:
            if any(has_key(s, k) for k in m["keys"]):
                mod = m["id"]
                break
        if mod:
            break
    return glyph, mod


