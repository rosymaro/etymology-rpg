def arrow(x0, y0, x1, y1, col=RED, w=7):
    import math
    a = math.atan2(y1 - y0, x1 - x0)
    hx, hy = x1 - math.cos(a) * 12, y1 - math.sin(a) * 12
    px, py = -math.sin(a) * 10, math.cos(a) * 10
    return [["l", [x0, y0, hx, hy], w, col], ["p", [x1, y1, hx + px, hy + py, hx - px, hy - py], col]]


